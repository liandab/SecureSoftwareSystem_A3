const express=require('express');
const helmet=require('helmet');
const cookieParser=require('cookie-parser');
const {apiLimit}=require('./middleware/limits');
const {issueCsrf,requireCsrf}=require('./middleware/csrf');
const auth=require('./routes/auth');
const vote=require('./routes/vote');
const admin=require('./routes/admin');
const {startMtlsResults}=require('./mtls-results');
const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(express.json({limit:'16kb'}));
app.use(cookieParser());
app.use('/api',apiLimit);
app.get('/api/health',(req,res)=>res.json({status:'ok',system:'EVP learning prototype'}));
app.get('/api/auth/csrf',issueCsrf);
app.use('/api',requireCsrf);
app.use('/api/auth',auth);
app.use('/api/vote',vote);
app.use('/api/admin',admin);
app.use((err,req,res,next)=>{console.error('Request error:',err.message);res.status(500).json({error:'Internal server error'});});
const port=Number(process.env.PORT||5000);
app.listen(port,'0.0.0.0',()=>console.log(`EVP demo backend listening on ${port}`));

startMtlsResults();
